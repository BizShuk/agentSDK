// Command gen materializes one pinned runnable package per catalog model —
// pkg/<PairSlug>/main.go for every provider-model pair whose metadata yields
// at least one runnable benchmark capability. Rerun after a catalog change:
//
//	go run ./benchmark/gen
//
// Regeneration only rewrites main.go files; tmp/ results are never touched.
// A generated main.go whose model left the catalog is removed (the directory
// and its tmp/ history stay).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/bizshuk/agentsdk/benchmark"
	"github.com/bizshuk/agentsdk/provider"
	_ "github.com/bizshuk/agentsdk/provider/all"
)

// GENERATED_MARKER identifies files this generator owns and may delete.
const GENERATED_MARKER = "Code generated by benchmark/gen"

var mainTemplate = template.Must(template.New("main").Parse(
	`// {{.Marker}}; DO NOT EDIT.

// Command {{.Dir}} benchmarks {{.Provider}} model {{.Model}} ({{.Capabilities}}).
// Credential: {{.Credential}}.
package main

import (
	"github.com/bizshuk/agentsdk/benchmark"
)

func main() {
	benchmark.Main({{printf "%q" .Provider}}, {{printf "%q" .Model}})
}
`))

type pkgData struct {
	Marker       string
	Dir          string
	Provider     string
	Model        string
	Capabilities string
	Credential   string
}

func main() {
	pkgRoot := filepath.Join(benchmark.Root(), "pkg")
	expected := map[string]bool{}
	count := 0

	for _, entry := range provider.Entries() {
		for _, spec := range benchmark.CatalogSpecs(entry.Name) {
			capabilities := benchmark.RunnableCapabilities(entry, spec)
			if len(capabilities) == 0 {
				continue
			}
			dir := benchmark.PairSlug(entry.Name, spec.ID)
			expected[dir] = true
			if err := writePackage(pkgRoot, dir, entry, spec, capabilities); err != nil {
				fatal(err)
			}
			count++
		}
	}

	removed, err := removeStale(pkgRoot, expected)
	if err != nil {
		fatal(err)
	}
	fmt.Printf("generated %d packages under %s (removed %d stale)\n", count, pkgRoot, removed)
}

func writePackage(pkgRoot, dir string, entry provider.Entry, spec provider.ModelSpec, capabilities []provider.Capability) error {
	var out bytes.Buffer
	err := mainTemplate.Execute(&out, pkgData{
		Marker:       GENERATED_MARKER,
		Dir:          dir,
		Provider:     entry.Name,
		Model:        spec.ID,
		Capabilities: joinCapabilities(capabilities),
		Credential:   credentialNote(entry.Metadata),
	})
	if err != nil {
		return fmt.Errorf("render %s: %w", dir, err)
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("format %s: %w", dir, err)
	}

	target := filepath.Join(pkgRoot, dir)
	if err := os.MkdirAll(target, 0o755); err != nil {
		return fmt.Errorf("create %s: %w", dir, err)
	}
	if err := os.WriteFile(filepath.Join(target, "main.go"), src, 0o644); err != nil {
		return fmt.Errorf("write %s/main.go: %w", dir, err)
	}
	return nil
}

func joinCapabilities(capabilities []provider.Capability) string {
	names := make([]string, 0, len(capabilities))
	for _, capability := range capabilities {
		names = append(names, string(capability))
	}
	return strings.Join(names, ",")
}

func credentialNote(m provider.Metadata) string {
	envs := append(append([]string{}, m.OAuthEnv...), m.APIKeyEnv...)
	if len(envs) == 0 {
		return "none"
	}
	return strings.Join(envs, " or ")
}

// removeStale deletes generator-owned main.go files whose model is no longer
// runnable, keeping the directory and any tmp/ results in place.
func removeStale(pkgRoot string, expected map[string]bool) (int, error) {
	entries, err := os.ReadDir(pkgRoot)
	if err != nil {
		if os.IsNotExist(err) {
			return 0, nil
		}
		return 0, err
	}
	removed := 0
	for _, entry := range entries {
		if !entry.IsDir() || expected[entry.Name()] {
			continue
		}
		mainPath := filepath.Join(pkgRoot, entry.Name(), "main.go")
		data, err := os.ReadFile(mainPath)
		if err != nil || !bytes.Contains(data, []byte(GENERATED_MARKER)) {
			continue
		}
		if err := os.Remove(mainPath); err != nil {
			return removed, fmt.Errorf("remove stale %s: %w", mainPath, err)
		}
		fmt.Printf("removed stale %s/main.go\n", entry.Name())
		removed++
	}
	return removed, nil
}

func fatal(err error) {
	fmt.Fprintf(os.Stderr, "gen: %v\n", err)
	os.Exit(1)
}
